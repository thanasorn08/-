# โค้ดเวอร์ชันใหม่ของฉัน
# พัฒนาจากต้นแบบ โดย: นางสาว ธนสร เกตุฉิม

print("=== โปรแกรมคำนวณพื้นที่รูปทรงต่างๆ ===")
print("1. สี่เหลี่ยมมุมฉาก")
print("2. สามเหลี่ยม")

choice = input("เลือกรูปทรงที่ต้องการคำนวณ (1 หรือ 2): ")

if choice == "1":
    w = float(input("กรอกความกว้าง: "))
    h = float(input("กรอกความยาว: "))
    area = w * h
    print(f"พื้นที่สี่เหลี่ยมมุมฉาก คือ: {area}")
elif choice == "2":
    b = float(input("กรอกความยาวฐาน: "))
    h = float(input("กรอกความสูง: "))
    area = 0.5 * b * h
    print(f"พื้นที่สามเหลี่ยม คือ: {area}")
else:
    print("ตัวเลือกไม่ถูกต้อง")
